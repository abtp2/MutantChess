export function getSavedBoardTheme() {
  const defaultTheme = BOARD_THEMES.find((t) => t.id === 'icy_sea') || BOARD_THEMES[0];
  if (typeof window === 'undefined') return defaultTheme;
  const saved = localStorage.getItem('mutant_board_theme');
  return BOARD_THEMES.find((t) => t.id === saved) || defaultTheme;
}

export function saveBoardTheme(themeId) {
  if (typeof window !== 'undefined') {
    localStorage.setItem('mutant_board_theme', themeId);
  }
}

