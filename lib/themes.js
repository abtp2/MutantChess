export function getThemeCssVariables(theme) {
  if (!theme) return {};
  return {
    '--theme-bg': theme.bg,
    '--theme-panel': theme.panel,
    '--theme-panel-sub': theme.panelSecondary || theme.panel,
    '--theme-sidebar': theme.sidebar || theme.panel,
    '--theme-border': theme.border,
    '--theme-border-light': theme.borderLight || theme.border,
    '--theme-accent': theme.accent,
    '--theme-accent-hover': theme.accentHover,
    '--theme-accent-shadow': theme.accentShadow || theme.accent,
    '--theme-accent-text': theme.accentText || '#ffffff',
    '--theme-btn-bg': theme.btnBg,
    '--theme-btn-hover': theme.btnHover,
    '--theme-btn-active': theme.btnActive,
    '--theme-text': theme.text,
    '--theme-text-sec': theme.textSecondary,
    '--theme-text-muted': theme.textMuted,
  };
}

export function applySiteThemeToDocument(theme) {
  if (typeof document === 'undefined' || !theme) return;
  const vars = getThemeCssVariables(theme);
  const root = document.documentElement;
  Object.entries(vars).forEach(([key, val]) => {
    root.style.setProperty(key, val);
  });
  if (document.body) {
    document.body.style.backgroundColor = theme.bg;
  }
}
